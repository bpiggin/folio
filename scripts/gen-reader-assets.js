// Bundles what the reader WebView needs into a TS module, so a message renders
// fully offline on the first frame:
//   - Mozilla Readability
//   - Phosphor icons used in the page
// Run `npm run gen:reader-assets` from the project root after upgrading any of these.
const fs = require('fs');
const path = require('path');

const ICONS = { archive: 'light/archive-light.svg' };

function main() {
  const readability = fs.readFileSync(require.resolve('@mozilla/readability/Readability.js'), 'utf8');

  const icons = {};
  for (const [key, file] of Object.entries(ICONS)) {
    icons[key] = fs
      .readFileSync(require.resolve(`@phosphor-icons/core/assets/${file}`), 'utf8')
      .replace('<svg ', '<svg aria-hidden="true" ')
      .trim();
  }

  const out = path.resolve('src', 'reader', 'assets.generated.ts');
  fs.writeFileSync(
    out,
    '// AUTO-GENERATED by scripts/gen-reader-assets.js — do not edit.\n' +
      `export const READABILITY_JS = ${JSON.stringify(readability)};\n` +
      `export const ICONS = ${JSON.stringify(icons, null, 2)} as const;\n`
  );
  console.log('wrote', path.relative(process.cwd(), out), fs.statSync(out).size, 'bytes');
}

main();
